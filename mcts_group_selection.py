def save_data(node: Node, spend: int, epoch: int, parent_value: float) -> list:
    """
    Collects the data to be put in the dataframe

    return: ["budget", "expandedBy", "objectiveValue","epoch", "treeDepth", "parentValue", "H","Rx","Ry","Rz","Cx"]
    """
    if node.isTerminal:
        parent_node = node.parent
        while parent_node.evaluation_value is None:
            parent_node = parent_node.parent
        value = parent_node.evaluation_value
    elif not node.parent:
        value = node.evaluation_value
    else:
        value = node.value / node.visits

    gate_counts = dict(node.state.circuit.count_ops())
    return [
        spend,
        node.group,
        value,
        epoch,
        node.tree_depth,
        parent_value,
        gate_counts["h"] if "h" in gate_counts.keys() else 0,
        gate_counts["rx"] if "rx" in gate_counts.keys() else 0,
        gate_counts["ry"] if "ry" in gate_counts.keys() else 0,
        gate_counts["rz"] if "rz" in gate_counts.keys() else 0,
        gate_counts["cx"] if "cx" in gate_counts.keys() else 0,
    ]


def mcts(
    root: Node,
    budget: int,  # Number of evaluations
    evaluation_function,  # Based on the quantum problem
    max_terminal_visits_percentage: float = 0.02,
    finite_progressive_widening: bool = True,
    # Default parameters
    branches=False,
    criteria: str = "value",
    epsilon: float = None,
    stop_deterministic: bool = False,
    roll_out_steps: int = 0,
    rollout_type: str = "classic",
    ucb_value: float = 0.4,
    pw_C=1,
    pw_alpha=0.3,
    verbose: bool = False,
    # Test dependendt parameters
    group_by_gates: bool = False,
    group_by_action: bool = False,
    terminal_nodes: bool = False,
    group_by_change: bool = False,
    group_by_swap: bool = False,
    collect_data: bool = False,
    selection_method: str = 'UCB',
    n: int = 2 # for n-grams selection method
) -> dict:
    best_node = root
    best_value = float("-inf")

    # a = add gate, d = delete gate, s = swap gates, c = change parameter
    original_root = root
    # dataframe to be filled with the selected node at each epoch
    objective_values = pd.DataFrame(
        columns=[
            "budget",
            "expandedBy",
            "objectiveValue",
            "epoch",
            "treeDepth",
            "parentValue",
            "H",
            "Rx",
            "Ry",
            "Rz",
            "Cx",
        ]
    )
    if verbose:
        print("Root Node:\n", root)

    evaluate(root, evaluation_function)
    root.visits = 1
    root.value = root.evaluation_value
    epoch_counter = 0

    max_terminal_visits = max_terminal_visits_percentage * budget
    spend = 0

    objective_values.loc[len(objective_values)] = save_data(
        root, spend, epoch_counter, 0
    )
    while spend < budget:
        epoch_counter += 1
        current_node = root

        # budget/20 means we permanently commit to best option once a node has used 5% of the total search budget.
        # if current_node.visits > budget / 20 and len(current_node.children) > 2:
        #     root = commit(epsilon, current_node, criteria)
        #     if verbose:
        #         print("Committed to", root)
        #     current_node = root

        if verbose:
            print("Epoch Counter: ", epoch_counter)

        # Selection
        while not current_node.isTerminal and current_node.is_fully_expanded(
            branches=branches,
            pw_C=pw_C,
            pw_alpha=pw_alpha,
            finite_progressive_widening=finite_progressive_widening,
        ):
            current_node = select(current_node, ucb_value, max_terminal_visits, method=selection_method, n=n)

            if verbose:
                print("Selection: ", current_node)

        initial_parent_value = current_node.value / current_node.visits

        # Expansion
        new_nodes = []
        if not current_node.isTerminal:
            if not current_node.is_finite:
                # If the current node is a group node witch is infinite expandable
                new_nodes.append(expand_infinite_group(current_node))
            elif current_node.to_expand and finite_progressive_widening:
                new_nodes.append(expand_finite_group(current_node))
            else:
                # Leaf node expansion
                new_nodes = expand_circuit(
                    current_node,
                    group_by_gates=group_by_gates,
                    group_by_action=group_by_action,
                    terminal_nodes=terminal_nodes,
                    group_by_change=group_by_change,
                    group_by_swap=group_by_swap,
                    finite_progressive_widening=finite_progressive_widening,
                )

        if not new_nodes and current_node.isTerminal:
            if collect_data:
                objective_values.loc[len(objective_values)] = save_data(
                    current_node, spend, epoch_counter, initial_parent_value
                )
            backpropagate(current_node, current_node.value / current_node.visits, selection_method, n)

        for new_node in new_nodes:
            if verbose:
                print("Node Expanded:\n", new_node)
            if not new_node:
                print(new_nodes)
            # Simulation
            if not new_node.isTerminal:
                if isinstance(roll_out_steps, int):
                    leaf_node = rollout(new_node, steps=roll_out_steps)
                    result = evaluate(leaf_node, evaluation_function)
                    spend += 1

                    if roll_out_steps > 1 and rollout_type != "classic":
                        node_to_evaluate = leaf_node
                        result_list = [result]
                        for _ in range(roll_out_steps):
                            result_list.append(
                                evaluate(node_to_evaluate.parent, evaluation_function)
                            )
                            node_to_evaluate = node_to_evaluate.parent
                        if rollout_type == "max":
                            result = max(result_list)
                        elif rollout_type == "mean":
                            result = sum(result_list) / len(result_list)
                        else:
                            raise NotImplementedError(
                                f"Rollout type '{rollout_type}' is not implemented."
                            )
                else:
                    raise TypeError("The variable roll_out_steps must be an integer")
            elif new_node.value == 0:
                result = evaluate(new_node, evaluation_function)
                spend += 1
            else:
                parent_node = new_node.parent
                while parent_node.evaluation_value is None:
                    parent_node = parent_node.parent
                result = parent_node.evaluation_value

            # update best value
            if result > best_value:
                best_value = result
                best_node = new_node

            if verbose:
                print("Reward: ", result)

            # Backpropagation
            backpropagate(new_node, result, selection_method, n)

            # Store data
            if result and collect_data:
                objective_values.loc[len(objective_values)] = save_data(
                    new_node, spend, epoch_counter, initial_parent_value
                )

    # Return the best
    best_greedy_node = original_root
    # path = []
    qc_path = []
    children, value, visits = [], [], []
    while not best_greedy_node.isTerminal and len(best_greedy_node.children) >= 1:
        # path.append(best_greedy_node)
        qc_path.append(best_greedy_node.state.circuit)
        children.append(len(best_greedy_node.children))
        value.append(best_greedy_node.value)
        visits.append(best_greedy_node.visits)
        best_greedy_node = best_greedy_node.best_child(criteria=criteria)

    return {
        "qc": qc_path,
        "children": children,
        "visits": visits,
        "value": value,
        "data": objective_values,
        "best_qc": best_node.state.circuit,
    }
